using System;
using System.Collections.Generic;
using System.IO;
using Fluorine.Generators;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace Fluorine.GeneratorTests
{
    public class ReactiveGeneratorTests
    {
        const string Stubs = @"
namespace Fluorine
{
    public static class Reactive {}
    public class AutoNotify {}

    [System.AttributeUsage(System.AttributeTargets.Property)]
    public sealed class ReactiveAttribute : System.Attribute {}

    [System.AttributeUsage(System.AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
    public sealed class AutoNotifyAttribute : System.Attribute {}

    public class Register<T>
    {
        public Register() {}
        public Register(T initial) {}
        public T Value { get; set; }
    }
}

namespace System.Runtime.CompilerServices
{
    internal static class IsExternalInit {}
}
";

        [Fact]
        public void ReactiveAutoPropertyBecomesRegisterAndAutoNotify()
        {
            var source = @"
using Fluorine;
namespace App
{
    public partial class Household : AutoNotify
    {
        [Reactive]
        public partial int HappyHousewife { get; set; }
    }
}
";
            var generated = Generate(source).Single();
            Assert.Equal(Normalize(@"// <auto-generated/>
#pragma warning disable
namespace App
{
    partial class Household
    {
        global::Fluorine.Register<int> happyHousewife = new global::Fluorine.Register<int>();

        [global::Fluorine.AutoNotify]
        public partial int HappyHousewife
        {
            get => happyHousewife.Value;
            set => happyHousewife.Value = value;
        }
    }
}
"), Normalize(generated.Text));
        }

        [Fact]
        public void SeveralShapesArePreserved()
        {
            var source = @"
using Fluorine;
using System.Collections.Generic;
namespace App
{
    public partial class Outer<T>
    {
        public partial class Inner
        {
            int item;

            [Reactive]
            public partial T Item { get; private set; }

            [Reactive]
            public partial int Class { get; init; }

            [Reactive]
            public partial int[] Flags { get; set; }

            [Reactive]
            public partial int? Maybe { get; set; }

            [Reactive]
            public partial List<string> Names { get; set; }

            [AutoNotify]
            public partial int Count { get; set; }

            [AutoNotify]
            public int Manual => 1;
        }
    }
}
";
            var generated = Generate(source).Single().Text;
            Assert.Contains("partial class Outer<T>", generated);
            Assert.Contains("partial class Inner", generated);
            Assert.Contains("global::Fluorine.Register<T> _item = new global::Fluorine.Register<T>();", generated);
            Assert.Contains("private set => _item.Value = value;", generated);
            Assert.Contains("global::Fluorine.Register<int> @class = new global::Fluorine.Register<int>();", generated);
            Assert.Contains("init => @class.Value = value;", generated);
            Assert.Contains("global::Fluorine.Register<int[]> flags = new global::Fluorine.Register<int[]>();", generated);
            Assert.Contains("global::Fluorine.Register<int?> maybe = new global::Fluorine.Register<int?>();", generated);
            Assert.Contains("global::Fluorine.Register<global::System.Collections.Generic.List<string>> names = new global::Fluorine.Register<global::System.Collections.Generic.List<string>>();", generated);
            Assert.Contains("global::Fluorine.Register<int> count = new global::Fluorine.Register<int>();", generated);
            var countAt = generated.IndexOf("partial int Count", StringComparison.Ordinal);
            Assert.True(countAt > 0);
            var window = generated.Substring(countAt - 40, 40);
            Assert.DoesNotContain("AutoNotify", window);
            Assert.DoesNotContain("Manual", generated);
        }

        [Fact]
        public void RecordsAndStructsKeepTheirKind()
        {
            var source = @"
using Fluorine;
namespace App
{
    public partial record Book
    {
        [Reactive]
        public partial int Pages { get; set; }
    }

    public partial struct Point
    {
        public Point() {}

        [Reactive]
        public partial int X { get; set; }
    }
}
";
            var generated = Generate(source);
            Assert.Equal(2, generated.Sources.Count);
            var text = generated.Sources[0].Text + generated.Sources[1].Text;
            Assert.Contains("partial record Book", text);
            Assert.Contains("partial struct Point", text);
            Assert.DoesNotContain("partial class Book", text);
            Assert.DoesNotContain("partial class Point", text);
        }

        [Fact]
        public void ExistingFieldNameIsLeftAlone()
        {
            var source = @"
using Fluorine;
namespace App
{
    public partial class Household : AutoNotify
    {
        int happyHousewife;

        [Reactive]
        public partial int HappyHousewife { get; set; }
    }
}
";
            var generated = Generate(source).Single().Text;
            Assert.Contains("global::Fluorine.Register<int> _happyHousewife = new global::Fluorine.Register<int>();", generated);
            Assert.Contains("get => _happyHousewife.Value;", generated);
        }

        [Fact]
        public void APropertyThatIsNotPartialIsReported()
        {
            var source = @"
using Fluorine;
namespace App
{
    public class Household : AutoNotify
    {
        [Reactive]
        public int HappyHousewife { get; set; }

        [Reactive]
        public partial int Needed { get; set; }

        [Reactive]
        public partial int Label => 1;

        [Reactive]
        public static partial int Total { get; set; }
    }
}
";
            var result = Generate(source, expectSuccess: false);
            Assert.Empty(result.Sources);
            Assert.Contains(result.Diagnostics, d => d.Id == "FLUORINE001");
            Assert.Contains(result.Diagnostics, d => d.Id == "FLUORINE002");
            Assert.Contains(result.Diagnostics, d => d.Id == "FLUORINE003");
            Assert.Contains(result.Diagnostics, d => d.Id == "FLUORINE004");
        }

        static Generation Generate(string source, bool expectSuccess = true)
        {
            var options = new CSharpParseOptions(LanguageVersion.CSharp13);
            var trees = new[]
            {
                CSharpSyntaxTree.ParseText(Stubs, options, path: "Stubs.cs"),
                CSharpSyntaxTree.ParseText(source, options, path: "Household.cs")
            };
            var references = new[]
            {
                MetadataReference.CreateFromFile(typeof(object).Assembly.Location)
            };
            var compilation = CSharpCompilation.Create(
                "gen",
                trees,
                references,
                new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

            GeneratorDriver driver = CSharpGeneratorDriver.Create(new ReactivePropertyGenerator());
            driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var updated, out var driverDiagnostics);
            var run = driver.GetRunResult();
            var sources = new List<Generated>();
            foreach (var result in run.Results)
            {
                foreach (var generated in result.GeneratedSources)
                    sources.Add(new Generated(generated.HintName, generated.SourceText.ToString()));
            }

            var diagnostics = new List<Diagnostic>();
            foreach (var diagnostic in driverDiagnostics)
                diagnostics.Add(diagnostic);
            foreach (var diagnostic in updated.GetDiagnostics())
            {
                if (diagnostic.Severity == DiagnosticSeverity.Error)
                    diagnostics.Add(diagnostic);
            }

            if (expectSuccess)
            {
                using (var pe = new MemoryStream())
                {
                    var emit = updated.Emit(pe);
                    Assert.True(emit.Success, string.Join(Environment.NewLine, emit.Diagnostics));
                }
                Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error && d.Id.StartsWith("FLUORINE"));
            }

            return new Generation(sources, diagnostics);
        }

        static string Normalize(string text)
        {
            return text.Replace("\r\n", "\n").Replace("\r", "\n");
        }

        sealed class Generation
        {
            public Generation(List<Generated> sources, List<Diagnostic> diagnostics)
            {
                Sources = sources;
                Diagnostics = diagnostics;
            }

            public List<Generated> Sources { get; }
            public List<Diagnostic> Diagnostics { get; }

            public Generated Single()
            {
                Assert.Single(Sources);
                return Sources[0];
            }
        }

        sealed class Generated
        {
            public Generated(string hint, string text)
            {
                Hint = hint;
                Text = text;
            }

            public string Hint { get; }
            public string Text { get; }
        }
    }
}
